# Data Receivers (Input Sources)
# ─────────────────────────────────────────────────────────────
class ReceiverBase:
    """Abstract base for data receivers."""

    def __init__(self):
        self._running = False

    def start(self):
        self._running = True

    def stop(self):
        self._running = False

    def readinto(self, buf: bytearray) -> int:
        """Read into buffer, return number of bytes read (0 = no data, -1 = EOF/error)."""
        raise NotImplementedError

    def is_active(self) -> bool:
        return self._running

class UARTReceiver(ReceiverBase):
    """
    Receive SWO data via UART-to-USB bridge.
    M487 PB8 (SWO) → UART-to-USB (FTDI/CH340/etc) → USB → PC

    Common UART-to-USB connections:
      - FTDI FT232R / FT230X
      - WCH CH340
      - Silabs CP2102

    UART settings for SWO:
      - Baud: 115200 ~ 2000000 (match TPI/ITM configuration)
      - Data bits: 8
      - Parity: None
      - Stop bits: 1
      - Flow control: None
    """

    def __init__(self, port: str, baud: int = 2000000,
                 timeout: float = 1.0):
        super().__init__()
        self.port = port
        self.baud = baud
        self.timeout = timeout
        self._ser: Optional[serial.Serial] = None
        self._buf = bytearray(4096)

    def _open(self):
        """Open serial port."""
        try:
            self._ser = serial.Serial(
                port=self.port,
                baudrate=self.baud,
                bytesize=serial.EIGHTBITS,
                parity=serial.PARITY_NONE,
                stopbits=serial.STOPBITS_ONE,
                timeout=self.timeout,
                xonxoff=False,
                rtscts=False,
                dsrdtr=False,
            )
            # Clear buffers
            self._ser.reset_input_buffer()
            self._ser.reset_output_buffer()
            print(f"[UART] Opened {self.port} @ {self.baud} baud")
            return True
        except serial.SerialException as e:
            print(f"[UART] Failed to open {self.port}: {e}")
            return False

    def start(self):
        if not self._open():
            return
        super().start()

    def stop(self):
        super().stop()
        if self._ser and self._ser.is_open:
            try:
                self._ser.close()
                print("[UART] Port closed")
            except Exception:
                pass

    def readinto(self, buf: bytearray) -> int:
        """Read available bytes into buf. Returns count or -1 on error."""
        if not self._ser or not self._ser.is_open:
            return -1
        try:
            # Read up to len(buf) bytes with short timeout
            data = self._ser.read(len(buf))
            n = len(data)
            if n > 0:
                buf[:n] = data
            return n
        except serial.SerialException as e:
            print(f"[UART] Read error: {e}")
            return -1

    @staticmethod
    def list_ports() -> List[Tuple[str, str]]:
        """List available COM ports with descriptions."""
        ports = serial.tools.list_ports.comports()
        return [(p.device, p.description or "Unknown") for p in ports]


class FileReceiver(ReceiverBase):
    """
    Read SWO data from a recorded binary file.
    Useful for offline analysis and testing.
    """

    def __init__(self, path: str, loop: bool = False):
        super().__init__()
        self.path = path
        self.loop = loop
        self._f: Optional[object] = None

    def start(self):
        try:
            self._f = open(self.path, "rb")
            print(f"[File] Opened {self.path}")
        except OSError as e:
            print(f"[File] Cannot open {self.path}: {e}")

    def stop(self):
        super().stop()
        if self._f:
            self._f.close()

    def readinto(self, buf: bytearray) -> int:
        """Read from file. Returns 0 when EOF (and loops if enabled)."""
        if not self._f:
            return -1
        try:
            data = self._f.read(len(buf))
            n = len(data)
            if n > 0:
                buf[:n] = data
                return n
            elif self.loop:
                self._f.seek(0)
                return self.readinto(buf)  # Tail-recurse
            else:
                return 0  # EOF
        except OSError as e:
            print(f"[File] Read error: {e}")
            return -1


