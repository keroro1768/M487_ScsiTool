# ─────────────────────────────────────────────────────────────
# ITM Protocol
# ─────────────────────────────────────────────────────────────
# ITM over SWO uses TPIU (Trace Port Interface Unit) formatter.
# Each word from ITM stimulus ports is wrapped with a frame byte.
#
# TPIU Frame format (for sync mode / Manchester):
#   Bit 7:    1 = overflow / lost data, 0 = normal
#   Bit 6:    1 = error, 0 = normal
#   Bits[5:3]: Source ID (usually 000 = ITM)
#   Bits[2:0]: Low 3 bits of source Stimulus Port
#
#   If bit 0 of the 8-bit frame is 1 → this byte is a STIMULUS byte
#   The stimulus port is frame[3:0] | (<<3)
#
# Simple Async/NRZ mode (used by many debuggers):
#   Raw bytes are sent directly; no framing needed at byte level.
#
# Manchester encoding (TPIU Sync mode):
#   Each bit time contains a transition; baud = bit rate.
#   Actual ITM bytes are 4B/5B encoded by TPIU.
#
# For most practical purposes (J-Link, pyocd, UART bridge):
#   The raw byte stream from SWO contains ITM stimulus bytes
#   with the MSB encoding the source port.
#
# Simplified decoding used here:
#   - Bytes with bit 7=0 are treated as raw data characters
#   - Bytes with bit 7=1 are treated as extended source info
#   - The firmware uses ITM_STIM_PORT = 0, so all trace bytes
#     arrive with source port field indicating port 0

class ITMState(Enum):
    IDLE       = auto()
    IN_FRAME   = auto()
    IN_SYNC    = auto()

# ─────────────────────────────────────────────────────────────
# Packet Types
# ─────────────────────────────────────────────────────────────
@dataclass
class ITMStimulusPacket:
    """A single stimulus byte from an ITM port."""
    port:   int       # ITM stimulus port (0-31)
    data:   int       # 8-bit data
    ts_ns:  int = 0   # Timestamp in nanoseconds (if available)

    def char_data(self) -> str:
        if 32 <= self.data < 127:
            return chr(self.data)
        return f"\\x{self.data:02X}"

@dataclass
class ITMTimestamp:
    """ITM timestamp event (generated by DWT cycle counter)."""
    ts_ns:  int
    cycles: int = 0

@dataclass
class ITMSync:
    """ITM sync packet (indicates frame boundary)."""
    pass

# ─────────────────────────────────────────────────────────────
# ITM Parser
# ─────────────────────────────────────────────────────────────
class ITMParser:
    """
    Parse raw SWO byte stream into ITM packets.

    Handles:
    - TPIU frame removal
    - Stimulus port demultiplexing
    - Timestamp extraction
    - Line reconstruction
    """

    def __init__(self, port_filter: Optional[int] = None):
        """
        Args:
            port_filter: Only show packets from this port (None = all ports)
        """
        self.port_filter = port_filter
        self._pkt_buf: List[ITMStimulusPacket] = []
        self._byte_accum: List[int] = []
        self._frame_buf: bytearray = bytearray()
        self._last_ts_ns: int = 0
        self._local_cycle_cnt: int = 0

        # ITM TPIU frame constants
        self._TPIU_FSYNC_MIN  = 0x80  # Frame sync prefix
        self._TPIU_FRAME_MASK = 0x07
        self._TPIU_SRC_SHIFT  = 3
        self._TPIU_STIM_VALID = 0x80  # Stimulus valid bit

        # Known sync sequences
        self._sync_known = bytes([0x00, 0x00, 0x00, 0x00, 0x80])

        # Trace state
        self._byte_count: int = 0
        self._lost_bytes: int = 0
        self._pkt_count: int = 0

    def parse_byte(self, b: int) -> List[object]:
        """
        Parse a single byte from the SWO stream.
        Returns a list of ITM objects (packets, timestamps, etc.)
        """
        out: List[object] = []
        self._byte_count += 1

        # Check for TPIU frame sync (0x80 followed by 0x00)
        if b == 0x80:
            self._frame_buf.clear()
            self._frame_buf.append(b)
            return out

        if self._frame_buf:
            self._frame_buf.append(b)
            # Check for complete sync frame
            if len(self._frame_buf) >= 5:
                self._frame_buf.clear()
                out.append(ITMSync())
                return out
            elif b != 0x00 and len(self._frame_buf) >= 2:
                # Not a valid sync frame, treat first byte as data
                # The 0x80 prefix is a frame sync marker
                self._frame_buf.clear()
                # Treat remaining bytes as raw
                for leftover in self._frame_buf:
                    sub = self._parse_raw_byte(leftover)
                    if sub:
                        out.extend(sub)
                self._frame_buf.clear()
            return out

        # Check for Manchester/Async 4B/5B sync patterns
        if self._byte_count <= 5 and b == 0x00:
            return out  # Skip leading zeros

        sub = self._parse_raw_byte(b)
        if sub:
            out.extend(sub)
        return out

    def _parse_raw_byte(self, b: int) -> List[object]:
        """Parse a raw byte as a potential ITM stimulus."""
        out: List[object] = []

        # ITM 8-bit Stimulus encoding:
        # The ITM sends one byte per stimulus port write.
        # At the TPIU level, the byte is framed with source info.
        #
        # Common simple format: raw bytes without framing (async UART mode)
        # In this case, every byte is a stimulus byte from port 0.
        #
        # Framed format (TPIU):
        #   bit 7 = 1: stimulus port info valid (bits 6:3 = source, bits 2:0 = port low)
        #   bit 7 = 0: just a regular byte
        #
        # For firmware using ITM_STIM_PORT=0 and simple SWO output,
        # we see raw ASCII characters and \\n for newlines.

        # Simple case: raw byte mode (no framing)
        # If b looks like printable ASCII or control char, treat as stimulus
        port = 0  # Default to port 0 (firmware uses this)

        if self.port_filter is not None and port != self.port_filter:
            return out

        pkt = ITMStimulusPacket(port=port, data=b, ts_ns=self._last_ts_ns)
        self._pkt_count += 1
        out.append(pkt)
        return out

    def parse_bytes(self, data: bytes) -> List[object]:
        """Parse a byte buffer."""
        out: List[object] = []
        for b in data:
            out.extend(self.parse_byte(b))
        return out

    @property
    def stats(self) -> dict:
        return {
            "bytes": self._byte_count,
            "packets": self._pkt_count,
            "lost": self._lost_bytes,
        }

# ─────────────────────────────────────────────────────────────
# Line Buffer (reconstructs lines from stimulus bytes)
# ─────────────────────────────────────────────────────────────
class LineBuffer:
    """Reconstruct complete lines from ITM stimulus bytes."""

    def __init__(self, max_line: int = 1024):
        self.buf = bytearray()
        self.max_line = max_line
        self._last_ts = ""

    def push(self, pkt: ITMStimulusPacket) -> Optional[Tuple[str, str, Optional[ITMStimulusPacket]]]:
        """
        Add a byte to the buffer.
        Returns (timestamp_str, line_str, last_byte) when a complete line is available,
        or None if line is incomplete.
        """
        if pkt.data == ord('\n'):
            # Complete line
            try:
                line = bytes(self.buf).decode('utf-8', errors='replace')
            except Exception:
                line = bytes(self.buf).hex(' ')
            ts = self._last_ts

            # Keep partial (no \\r)
            if line.endswith('\r'):
                line = line[:-1]

            self.buf.clear()
            return (ts, line, pkt)
        elif pkt.data == ord('\r'):
            # \\r\\n line ending
            if self.buf:
                try:
                    line = bytes(self.buf).decode('utf-8', errors='replace')
                except Exception:
                    line = bytes(self.buf).hex(' ')
                self.buf.clear()
                return (self._last_ts, line, pkt)
            return None
        else:
            if len(self.buf) < self.max_line:
                self.buf.append(pkt.data)
            return None

    def flush(self) -> Optional[Tuple[str, str, None]]:
        """Return any remaining content in buffer."""
        if self.buf:
            try:
                line = bytes(self.buf).decode('utf-8', errors='replace')
            except Exception:
                line = bytes(self.buf).hex(' ')
            self.buf.clear()
            return (self._last_ts, line, None)
        return None

# ─────────────────────────────────────────────────────────────
# Output Formatter
# ─────────────────────────────────────────────────────────────
class OutputFormatter:
    """Format and colorize ITM output for console."""

    def __init__(self, use_color: bool = True, show_hex: bool = False,
                 show_timestamps: bool = True, show_stats: bool = False):
        self.use_color     = use_color
        self.show_hex      = show_hex
        self.show_ts       = show_timestamps
        self.show_stats    = show_stats
        self._line_count   = 0
        self._parser: Optional[ITMParser] = None

        # ANSI color map
        self._c = {
            "err":   Col.ERR,
            "warn":  Col.WARN,
            "info":  Col.INFO,
            "dbg":   Col.DBG,
            "ts":    Col.TS,
            "reset": Col.RESET,
        }

    def _color(self, key: str, text: str) -> str:
        if not self.use_color:
            return text
        return f"{self._c[key]}{text}{self._c['reset']}"

    def _detect_level(self, line: str) -> str:
        """Detect log level from line content."""
        upper = line.upper()
        if "[ERR"  in upper or " ERR" in upper: return "err"
        if "[WARN" in upper or " WARN" in upper: return "warn"
        if "[INFO" in upper or " INFO" in upper: return "info"
        if "[DBG"  in upper or " DBG" in upper:  return "dbg"
        if "[TRC"  in upper or " TRC" in upper:  return "dbg"  # trace → dbg color
        return "info"

    def _detect_module(self, line: str) -> str:
        """Detect module from line content and return color."""
        upper = line.upper()
        if "[USB]" in upper:  return Col.USB
        if "[MSC]" in upper:  return Col.MSC
        if "[I2C]" in upper:  return Col.I2C
        if "[HID]" in upper:  return Col.HID
        return ""

    def print_line(self, ts: str, line: str, last_pkt: Optional[ITMStimulusPacket] = None):
        """Print a complete log line with optional colorization."""
        self._line_count += 1

        level_color = self._detect_level(line)
        module_color = self._detect_module(line)

        # Timestamp
        if self.show_ts and ts:
            ts_out = self._color("ts", f"[{ts}]")
        else:
            ts_out = ""

        # Level color tag
        tag = ""
        if level_color == "err":
            tag = self._color("err", " ✗")
        elif level_color == "warn":
            tag = self._color("warn", " ⚠")
        elif level_color == "info":
            tag = self._color("info", " ℹ")
        elif level_color == "dbg":
            tag = self._color("dbg", " ◷")

        # Module color
        if module_color:
            line_out = f"{module_color}{line}{Col.RESET if self.use_color else ''}"
        else:
            line_out = line

        # Assemble
        parts = [x for x in [ts_out, tag, line_out] if x]
        print(" ".join(parts))

        # Show hex dump for non-printable content
        if self.show_hex and last_pkt:
            try:
                hex_str = " ".join(f"{b:02X}" for b in line.encode('utf-8', errors='replace'))
            except Exception:
                hex_str = "???"
            print(self._color("ts", f"    HEX: {hex_str}"))

    def print_raw(self, data: bytes):
        """Print raw hex dump."""
        for i in range(0, len(data), 16):
            chunk = data[i:i+16]
            hex_str = " ".join(f"{b:02X}" for b in chunk)
            ascii_str = "".join(chr(b) if 32 <= b < 127 else "." for b in chunk)
            print(f"  {i:04X}: {hex_str:<48}  {ascii_str}")

    def print_stats(self, parser: 'ITMParser'):
        """Print parser statistics."""
        s = parser.stats
        print(self._color("ts",
            f"[ITM Stats] bytes={s['bytes']} packets={s['packets']} lost={s['lost']}"))

    def print_welcome(self, args):
        """Print startup banner."""
        print(c(Col.HDR, "═" * 60))
        print(c(Col.HDR, "  ITM SWO Trace Viewer  (M487 Cortex-M4)"))
        print(c(Col.HDR, "═" * 60))
        mode = "unknown"
        if args.get("uart"):
            mode = f"UART {args['uart']} @ {args.get('baud', 2000000)} baud"
        elif args.get("file"):
            mode = f"File: {args['file']}"
        elif args.get("jlink"):
            mode = "J-Link SWO"
        print(f"  Mode  : {mode}")
        print(f"  Filter: port={args.get('port', 'all')}")
        print(f"  Color : {args.get('color', True)}")
        print(c(Col.HDR, "─" * 60))
        print(c(Col.DIM,  "  Press Ctrl+C to exit..."))
        print(c(Col.HDR, "═" * 60) + "\n")

