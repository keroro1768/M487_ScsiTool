class StdinReceiver(ReceiverBase):
    """
    Read SWO data from stdin.
    Useful for piping from other tools.
    """

    def __init__(self):
        super().__init__()

    def start(self):
        super().start()
        print("[Stdin] Reading SWO data from stdin...")

